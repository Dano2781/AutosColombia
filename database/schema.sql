CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento VARCHAR(10) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL UNIQUE,
    nombre_completo VARCHAR(120) NOT NULL,
    telefono VARCHAR(25),
    email VARCHAR(120),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO','INACTIVO')),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vehiculo (
    id_vehiculo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
    placa VARCHAR(6) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('AUTOMOVIL','MOTOCICLETA','CAMIONETA','OTRO')),
    marca VARCHAR(50),
    color VARCHAR(30),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE IF NOT EXISTS mensualidad (
    id_mensualidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vehiculo BIGINT NOT NULL REFERENCES vehiculo(id_vehiculo),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(12) NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA','VENCIDA','SUSPENDIDA')),
    CONSTRAINT ck_mensualidad_fechas CHECK (fecha_fin >= fecha_inicio)
);
CREATE INDEX IF NOT EXISTS idx_mensualidad_vigencia
    ON mensualidad(id_vehiculo, estado, fecha_inicio, fecha_fin);

CREATE TABLE IF NOT EXISTS celda (
    id_celda BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('AUTOMOVIL','MOTOCICLETA','MIXTA')),
    estado VARCHAR(10) NOT NULL DEFAULT 'LIBRE' CHECK (estado IN ('LIBRE','OCUPADA','INACTIVA')),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS operario (
    id_operario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(120) NOT NULL,
    usuario_acceso VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    rol VARCHAR(15) NOT NULL DEFAULT 'OPERARIO' CHECK (rol IN ('OPERARIO','SUPERVISOR')),
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE IF NOT EXISTS movimiento (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mensualidad BIGINT NOT NULL REFERENCES mensualidad(id_mensualidad),
    id_celda BIGINT NOT NULL REFERENCES celda(id_celda),
    id_operario_entrada BIGINT NOT NULL REFERENCES operario(id_operario),
    id_operario_salida BIGINT REFERENCES operario(id_operario),
    fecha_hora_entrada TIMESTAMP NOT NULL,
    fecha_hora_salida TIMESTAMP,
    estado VARCHAR(10) NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA','CERRADA')),
    CONSTRAINT ck_salida_posterior CHECK (fecha_hora_salida IS NULL OR fecha_hora_salida >= fecha_hora_entrada)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_movimiento_abierto_por_mensualidad
    ON movimiento(id_mensualidad) WHERE estado = 'ABIERTA';
CREATE INDEX IF NOT EXISTS idx_movimiento_celda_estado ON movimiento(id_celda, estado);
CREATE INDEX IF NOT EXISTS idx_movimiento_entrada ON movimiento(fecha_hora_entrada);

CREATE TABLE IF NOT EXISTS pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mensualidad BIGINT NOT NULL UNIQUE REFERENCES mensualidad(id_mensualidad),
    id_operario_registro BIGINT NOT NULL REFERENCES operario(id_operario),
    fecha_hora_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valor NUMERIC(14,2) NOT NULL CHECK (valor > 0),
    medio_pago VARCHAR(15) NOT NULL CHECK (medio_pago IN ('EFECTIVO','TARJETA','TRANSFERENCIA')),
    referencia VARCHAR(60),
    estado VARCHAR(10) NOT NULL DEFAULT 'PAGADO' CHECK (estado IN ('PAGADO','ANULADO')),
    fecha_hora_anulacion TIMESTAMP,
    id_operario_anulacion BIGINT REFERENCES operario(id_operario),
    motivo_anulacion VARCHAR(250),
    CONSTRAINT ck_pago_referencia CHECK (
        medio_pago = 'EFECTIVO' OR (referencia IS NOT NULL AND BTRIM(referencia) <> '')
    ),
    CONSTRAINT ck_pago_anulacion CHECK (
        (estado = 'PAGADO' AND fecha_hora_anulacion IS NULL
            AND id_operario_anulacion IS NULL AND motivo_anulacion IS NULL)
        OR
        (estado = 'ANULADO' AND fecha_hora_anulacion IS NOT NULL
            AND id_operario_anulacion IS NOT NULL
            AND motivo_anulacion IS NOT NULL AND BTRIM(motivo_anulacion) <> '')
    )
);
CREATE INDEX IF NOT EXISTS idx_pago_fecha_estado ON pago(fecha_hora_pago DESC, estado);
CREATE INDEX IF NOT EXISTS idx_pago_operario_registro ON pago(id_operario_registro);

CREATE TABLE IF NOT EXISTS auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_operario BIGINT REFERENCES operario(id_operario),
    operacion VARCHAR(50) NOT NULL,
    resultado VARCHAR(10) NOT NULL CHECK (resultado IN ('ACEPTADA','RECHAZADA')),
    detalle VARCHAR(500),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
